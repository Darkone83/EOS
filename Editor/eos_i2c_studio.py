    def add_reg(self, name="register", width=1):
        self.tbl_regs.blockSignals(True); r=self.tbl_regs.rowCount(); self.tbl_regs.insertRow(r)
        self.tbl_regs.setItem(r,0,QTableWidgetItem(name)); self.tbl_regs.setItem(r,1,QTableWidgetItem(str(width))); off=QTableWidgetItem("auto"); off.setFlags(off.flags() & ~Qt.ItemIsEditable); self.tbl_regs.setItem(r,2,off)
        self.tbl_regs.blockSignals(False); self.refresh_all()
    def remove_reg(self):
        r=self.tbl_regs.currentRow();
        if r>=0: self.tbl_regs.removeRow(r); self.refresh_all()

    def add_cmd(self, name="COMMAND", code=1, op="Write Register", tx="", rx="", fixed=""):
        self.tbl_cmds.blockSignals(True); r=self.tbl_cmds.rowCount(); self.tbl_cmds.insertRow(r)
        self.tbl_cmds.setItem(r,0,QTableWidgetItem(name)); self.tbl_cmds.setItem(r,1,QTableWidgetItem(f"0x{code:02X}"))
        combo=QComboBox(); combo.addItems(OPS); combo.setCurrentText(op); combo.currentTextChanged.connect(self.refresh_all); self.tbl_cmds.setCellWidget(r,2,combo)
        txc=QComboBox(); rxc=QComboBox();
        names=[clean_name(self.tbl_regs.item(i,0).text(), "REG") for i in range(self.tbl_regs.rowCount()) if self.tbl_regs.item(i,0)]
        txc.addItems([""]+names); rxc.addItems([""]+names); txc.setCurrentText(tx); rxc.setCurrentText(rx)
        txc.currentTextChanged.connect(self.refresh_all); rxc.currentTextChanged.connect(self.refresh_all)
        self.tbl_cmds.setCellWidget(r,3,txc); self.tbl_cmds.setCellWidget(r,4,rxc); self.tbl_cmds.setItem(r,5,QTableWidgetItem(fixed))
        self.tbl_cmds.blockSignals(False); self.refresh_all()
    def remove_cmd(self):
        r=self.tbl_cmds.currentRow();
        if r>=0: self.tbl_cmds.removeRow(r); self.refresh_all()

    def _regs(self):
        out=[]; off=2; seen=set(); self.tbl_regs.blockSignals(True)
        for r in range(self.tbl_regs.rowCount()):
            name=clean_name(self.tbl_regs.item(r,0).text() if self.tbl_regs.item(r,0) else "REG", "REG")
            try: width=int(self.tbl_regs.item(r,1).text())
            except Exception: width=1
            width=max(1,min(64,width));
            if name in seen: name=f"{name}_{r+1}"
            seen.add(name); out.append(RegDef(name,width,off))
            self.tbl_regs.setItem(r,2,QTableWidgetItem(f"0x{off:02X}–0x{off+width-1:02X}" if width>1 else f"0x{off:02X}")); self.tbl_regs.item(r,2).setFlags(self.tbl_regs.item(r,2).flags() & ~Qt.ItemIsEditable)
            off += width
        self.tbl_regs.blockSignals(False); return out

    def _sync_reg_combos(self, regs):
        names=[r.name for r in regs]
        for row in range(self.tbl_cmds.rowCount()):
            for col in (3,4):
                cb=self.tbl_cmds.cellWidget(row,col)
                if not isinstance(cb,QComboBox): continue
                cur=cb.currentText(); cb.blockSignals(True); cb.clear(); cb.addItems([""]+names)
                if cur in names: cb.setCurrentText(cur)
                cb.blockSignals(False)

    def _cmds(self):
        out=[]; seen=set()
        for r in range(self.tbl_cmds.rowCount()):
            name=clean_name(self.tbl_cmds.item(r,0).text() if self.tbl_cmds.item(r,0) else "CMD", "CMD")
            if name in seen: name=f"{name}_{r+1}"
            seen.add(name)
            t=(self.tbl_cmds.item(r,1).text() if self.tbl_cmds.item(r,1) else "1").strip()
            try: code=int(t,0)
            except Exception: code=r+1
            code=max(0,min(255,code))
            combo=self.tbl_cmds.cellWidget(r,2); op=combo.currentText() if combo else OPS[0]
            txw=self.tbl_cmds.cellWidget(r,3); rxw=self.tbl_cmds.cellWidget(r,4)
            tx=clean_name(txw.currentText(),"") if txw and txw.currentText().strip() else ""
            rx=clean_name(rxw.currentText(),"") if rxw and rxw.currentText().strip() else ""
            fixed=self.tbl_cmds.item(r,5).text().strip() if self.tbl_cmds.item(r,5) else ""
            out.append(CmdDef(name,code,op,tx,rx,fixed))
        return out

    def _doorbell_code(self):
        return build_doorbell_script(target=self.target,scl=self.cb_scl.currentText(),sda=self.cb_sda.currentText(),dev_name=self.ed_dev.text(),addr=self.sp_addr.value(),poll_ms=self.sp_poll.value(),regs=self._regs(),cmds=self._cmds())

    def _quick_code(self):
        return generate_simple(target=self.target,scl=self.cb_scl.currentText(),sda=self.cb_sda.currentText(),dev_name=self.ed_dev.text(),addr=self.sp_addr.value(),recipe=self.cb_recipe.currentText(),write_hex=self.ed_write.text(),read_len=self.sp_readlen.value(),dest=self.sp_dest.value(),interval=self.sp_interval.value())

    def current_code(self): return self._quick_code() if self.tabs.currentIndex()==0 else self._doorbell_code()

    def refresh_all(self,*_):
        if not hasattr(self,"quick_preview"): return
        self.quick_preview.setPlainText(self._quick_code())
        regs=self._regs();
        if hasattr(self,"tbl_cmds"): self._sync_reg_combos(regs)
        cmds=self._cmds() if hasattr(self,"tbl_cmds") else []
        if hasattr(self,"db_preview"):
            self.db_preview.setPlainText(self._doorbell_code())
            m=["pin-def 0 mailbox", "0x00  CMD", "0x01  DOORBELL   (0 IDLE / 1 PENDING / 2 BUSY / 3 READY)"]
            for r in regs: m.append(f"0x{r.offset:02X}  {r.name:<14} width {r.width}")
            m += ["0xFF  RESULT     (0 OK / 1 NACK_ADDR / 2 NACK_DATA / 3 TIMEOUT / 4 STUCK)", "", "Commands:"]
            for c in cmds: m.append(f"0x{c.code:02X}  {c.name}  → {c.op}")
            m += ["", "Xbox host flow:", "1. Write command registers", "2. Write CMD code", "3. Set DOORBELL = 1 (PENDING)", "4. Wait for DOORBELL = 3 (READY)", "5. Read response registers", "6. Set DOORBELL = 0 (IDLE)"]
            self.map_view.setPlainText("\n".join(m))
        problems=[]
        if self.cb_scl.currentText()==self.cb_sda.currentText(): problems.append("SCL and SDA must use different pins")
        if regs and regs[-1].offset+regs[-1].width>0xF8: problems.append("register map reaches reserved volatile space 0xF8–0xFF")
        if self.tabs.currentIndex()==0:
            if self.cb_recipe.currentText() in ("Write Loop","Write + Read Loop") and parse_hex_bytes(self.ed_write.text()) is None: problems.append("write bytes must be an even number of hex digits (max 256 bytes)")
            if self.cb_recipe.currentText() in ("Read Loop","Write + Read Loop") and self.sp_dest.value()+self.sp_readlen.value()>0xF8: problems.append("read destination would overlap reserved volatile space 0xF8–0xFF")
        if self.tabs.currentIndex()==1:
            rnames={r.name for r in regs}
            codes=[c.code for c in cmds]
            if len(codes)!=len(set(codes)): problems.append("command codes must be unique")
            for c in cmds:
                if c.op in ("Write Register","Write Register + Read Register") and c.tx not in rnames: problems.append(f"{c.name}: choose a valid TX register")
                if c.op in ("Read Register","Write Register + Read Register") and c.rx not in rnames: problems.append(f"{c.name}: choose a valid RX register")
                if c.op=="Write Fixed Bytes" and parse_hex_bytes(c.fixed) is None: problems.append(f"{c.name}: Fixed Hex is invalid")
        # refresh_all() is also used while the default Doorbell rows are being
        # seeded inside _build_doorbell_tab().  At that point the bottom status
        # bar has not been constructed yet, so keep validation state but defer
        # touching the widget until it exists.
        self._problems = problems
        if hasattr(self, "lbl_status"):
            self.lbl_status.setText("⚠ " + problems[0] if problems else "✓ ready")
            self.lbl_status.setStyleSheet("color:#ff8a80;" if problems else "color:#7ee787;")

    def _blocked(self):
        self.refresh_all()
        if self._problems:
            QMessageBox.warning(self,"Fix these first","\n".join("• "+p for p in self._problems)); return True
        return False
    def copy_code(self):
        if self._blocked(): return
        QApplication.clipboard().setText(self.current_code()); QMessageBox.information(self,"Copied","I²C script copied to the clipboard.")
    def open_new(self):
        if self._blocked(): return
        if self.parent_win and hasattr(self.parent_win,"add_tab"):
            self.parent_win.add_tab(self.current_code());
            if hasattr(self.parent_win,"run_lint"): self.parent_win.run_lint()
            self.accept()
        else: self.copy_code()

