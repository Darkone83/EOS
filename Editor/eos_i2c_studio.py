def usable_pins(target: str):
    return [f"EXP{i}" for i in range(4, 9)] if target.upper() == "HD" else [f"EXP{i}" for i in range(1, 9)]


def clean_name(s: str, default="ITEM"):
    s = re.sub(r"[^A-Za-z0-9_]", "_", (s or "").strip())
    if not s: s = default
    if s[0].isdigit(): s = "N_" + s
    return s.upper()[:24]


def parse_hex_bytes(text: str):
    t = re.sub(r"[^0-9A-Fa-f]", "", text or "")
    if len(t) % 2: return None
    if len(t) > 512: return None
    return t.upper()


def generate_simple(*, target="NOHD", scl="EXP5", sda="EXP6", dev_name="DEVICE", addr=0x40,
                    recipe="Write + Read Loop", write_hex="0180", read_len=2, dest=0x20, interval=100):
    dev = clean_name(dev_name, "DEVICE")
    payload = parse_hex_bytes(write_hex)
    lines = ["# Generated by EOS I2C Studio — Quick Recipe", f"TARGET {target.upper()}",
             f"USES {scl} {sda} AS I2C", f"DEF {dev} 0x{addr:02X}", "DEF RESULT 0xFF"]
    if payload:
        lines += ["", f"DATA tx {payload}"]
    lines += ["", "LOOP"]
    if recipe in ("Write Loop", "Write + Read Loop"):
        if payload: lines.append(f"  I2CW {dev} tx")
    if recipe in ("Read Loop", "Write + Read Loop"):
        lines.append(f"  I2CR {dev} {read_len} 0x{dest:02X}")
    lines += [f"  DELAY {interval}", "ENDLOOP", "END"]
    return "\n".join(lines) + "\n"


@dataclass
class RegDef:
    name: str
    width: int
    offset: int


@dataclass
class CmdDef:
    name: str
    code: int
    op: str
    tx: str
    rx: str
    fixed: str


OPS = ["Write Register", "Read Register", "Write Fixed Bytes", "Write Register + Read Register"]


def build_doorbell_script(*, target, scl, sda, dev_name, addr, poll_ms, regs, cmds):
    dev = clean_name(dev_name, "DEVICE")
    lines = ["# Generated by EOS I2C Studio — Doorbell Command Builder", f"TARGET {target.upper()}",
             f"USES {scl} {sda} AS I2C"]
    for r in regs:
        lines.append(f"  REG {r.name.lower()} WIDTH {r.width}")
    lines += ["", "# Mailbox map for pin-def 0", "DEF CMD0 0x00", "DEF DB0 0x01"]
    for r in regs:
        lines.append(f"DEF {r.name} 0x{r.offset:02X}")
    lines += [f"DEF {dev} 0x{addr:02X}", "DEF RESULT 0xFF", ""]
    for c in cmds:
        lines.append(f"DEF CMD_{c.name} 0x{c.code:02X}")

    data_defs = []
    handlers = []
    regmap = {r.name: r for r in regs}
    for c in cmds:
        acts = []
        if c.op in ("Write Register", "Write Register + Read Register"):
            r = regmap.get(c.tx)
            if r: acts.append(f"I2CW {dev} VOL {r.name} {r.width}")
        if c.op == "Write Fixed Bytes":
            hx = parse_hex_bytes(c.fixed) or "00"
            dn = f"payload_{c.name.lower()}"
            data_defs.append((dn, hx)); acts.append(f"I2CW {dev} {dn}")
        if c.op in ("Read Register", "Write Register + Read Register"):
            r = regmap.get(c.rx)
            if r: acts.append(f"I2CR {dev} {r.width} {r.name}")
        if not acts: acts = ["NOP"]
        handlers.append((c, acts))

    guarded_count = 1  # SETMAIL DB0 2
    for _, acts in handlers: guarded_count += 1 + len(acts)  # IFMAIL + action lines
    guarded_count += 2  # READY + small delay

    lines += ["", "LOOP", f"  IFMAIL DB0 EQ 1 {guarded_count}", "    SETMAIL DB0 2"]
    for c, acts in handlers:
        lines.append(f"    IFMAIL CMD0 EQ CMD_{c.name} {len(acts)}")
        for a in acts: lines.append("      " + a)
    lines += ["    SETMAIL DB0 3", "    DELAY 2", f"  DELAY {poll_ms}", "ENDLOOP", "END"]
    if data_defs:
        lines += [""]
        for n, hx in data_defs: lines.append(f"DATA {n} {hx}")
    return "\n".join(lines).rstrip() + "\n"


